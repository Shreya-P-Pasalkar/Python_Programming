import numpy as np
import math

#########################################################################################
#   Function Name : main
#   Description   : Entry-point funtion
#   Input         : None
#   Output        : None
#   Date          : 03/05/026
#   Author        : Shreya Pramod Pasalkar
#########################################################################################
def main() :
    #---------------------------------------------------------------------
    #   Step 1 : Inputs(X_i)
    #---------------------------------------------------------------------
    X = np.array([2,3])

    #---------------------------------------------------------------------
    #   Step 2 : Weights(W_i)
    #---------------------------------------------------------------------
    W = np.array([0.4,0.5])

    #---------------------------------------------------------------------
    #   Step 3 : Define Bias
    #---------------------------------------------------------------------
    bias = 0.5

    #---------------------------------------------------------------------
    #   Step 4 : Calculate Weighted Sum
    #   Weighted_Sum = (x1w1 + x2w2) + bias
    #---------------------------------------------------------------------
    Weighted_Sum = np.dot(X,W) + bias

    #---------------------------------------------------------------------
    #   Step 5 : Apply Sigmoid Function
    #---------------------------------------------------------------------
    Output = 1 / (1 + (math.exp(-Weighted_Sum)))

    #---------------------------------------------------------------------
    #   Step 6 : Display Output
    #---------------------------------------------------------------------
    print("- "*50)
    print(("Single Neuron Implementation").center(100))
    print("- "*50)

    print(f"Inputs : {X}")
    print(f"Weights : {W}")
    print(f"bias : {bias}")
    print(f"Weighted Sum : {Weighted_Sum}")
    print(f"Final Output : {Output}")

    if(Output <= 0.5) :
        print("Output is close to 0 which indicated negative impact")
    else :
        print("Output is close to 1 which indicated positive impact")

    print("- "*50)

#########################################################################################
#   Starter
#########################################################################################
if __name__ == "__main__" :
    main()


